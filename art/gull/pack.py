#!/usr/bin/env python3
"""Pack the baked SVOX bundle (art/gull/svox) into one ES module the game imports: src/ui/gull/gulldata.js.
RIG = rig.json without file paths; VOX = base64 of zlib(deflate) of every part's albedo volume then its normal/AO volume,
in rig order, each in texImage3D order ((z*sy + y)*sx + x)*4. The page inflates it with DecompressionStream('deflate')."""
import base64, json, sys, zlib
from pathlib import Path
sys.path.insert(0, '/home/ubuntu/hybrid-voxel-sprite/skills/hybrid-voxel-sprite/scripts')
import svox_cli as sv
HERE = Path(__file__).resolve().parent
B = HERE / 'svox'
rig = json.loads((B / 'rig.json').read_text())
blob = bytearray()
for p in rig['parts']:
    blob += sv.read_part_volume(B, p, 'albedoPath') + sv.read_part_volume(B, p, 'normalAoPath')
    for k in ('albedoPath', 'normalAoPath', 'albedoLayout'): p.pop(k, None)
for k in ('normalAo', 'generator', 'source', 'framing'): rig.pop(k, None)
z = zlib.compress(bytes(blob), 9)
out = HERE.parent.parent / 'src/ui/gull/gulldata.js'
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text('// Generated by art/gull/pack.py from art/gull/svox (sculpted by art/gull/sculpt.py). Do not edit by hand.\n'
               '// RIG: the SVOX rig (svox.rig/v1). VOX: base64 zlib of each part\'s albedo then normal/AO volume, in rig order.\n'
               'export const RIG = ' + json.dumps(rig, separators=(',', ':'), ensure_ascii=False) + ';\n'
               'export const VOX = \'' + base64.b64encode(z).decode() + '\';\n')
print('pack: %d parts, %d raw bytes -> %d deflated -> %s (%d bytes)' % (len(rig['parts']), len(blob), len(z), out, out.stat().st_size))
