// Two example friends next to island 1, each with a few buildings and half a bridge toward island 1.
import fs from 'fs';
import { makeIsles, placePlot, PLOT, centerOf } from '../src/v2/isles.js';
const friends = {
  'seed-a': { slot: 2, name: '예시 친구 하나', half: { 1: 2 }, wants: [['bakery', '아침마다 줄 서는 동네 빵집', 'M', { style: 'brick', accent: '#c0392b' }], ['house', '빨간 지붕 2층 단독주택', 'S', { levels: 2 }], ['house', '마당 있는 작은 집', 'S', {}]] },
  'seed-b': { slot: 6, name: '예시 친구 둘', half: { 1: 3 }, wants: [['pc_bang', '네온사인 가득한 PC방', 'M', { night: true, accent: '#ff4fa3' }], ['apartment', '12층 아파트', 'L', { levels: 12 }], ['kiosk', '겨울 골목의 작은 붕어빵 노점', 'S', { hero: 'food_cart', sign: { icon: 'fish' } }]] },
};
const world = makeIsles(new Set([2, 6]), new Map());
const out = {};
for (const [uid, f] of Object.entries(friends)) {
  const taken = new Set(), plots = {}, [cx, cz] = centerOf(f.slot);
  for (const [type, line, size, extra] of f.wants) {
    const n = PLOT[size]; let spot = null;
    for (let z = cz - 8; z <= cz + 8 && !spot; z++) for (let x = cx - 8; x <= cx + 8 && !spot; x++) { const door = placePlot(world, f.slot, x, z, n, taken); if (door) spot = { x, z, door }; }
    if (!spot) { console.log('no spot', uid, type); continue; }
    for (let i = spot.x; i < spot.x + n; i++) for (let k = spot.z; k < spot.z + n; k++) taken.add(i + ',' + k);
    plots[`${f.slot}_${spot.x}_${spot.z}`] = { x: spot.x, z: spot.z, size, door: spot.door, b: { input: { type, name: line.split(' ').slice(-1)[0], scale: size, ...extra }, line, at: 1 } };
  }
  out[uid] = { slot: f.slot, at: 1, name: f.name, plots, half: f.half, wallet: { coins: 0, unlocked: ['S', 'M', 'L'] } };
}
fs.writeFileSync(new URL('../examples/isles-seed.js', import.meta.url), '// Example friends for the archipelago; generated by scripts/make-isles-seed.mjs.\nexport const ISLES_SEED = ' + JSON.stringify(out, null, 1) + ';\n');
for (const [uid, d] of Object.entries(out)) fs.writeFileSync(`/tmp/claude-1001/-home-ubuntu-crashbang-heroes/1fe2db80-4c05-4aea-a7af-e2b5546fe96b/scratchpad/isles-${uid}.json`, JSON.stringify(d));
console.log(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, Object.keys(v.plots)])));
