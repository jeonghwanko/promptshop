// Places the example buildings on valid plots (same rules as the page) and writes examples/world-seed.js.
import fs from 'fs';
import { toXY, search } from '../src/v2/geo.js';
import { makeArea, canPlace, takenTiles } from '../src/v2/area.js';
import { SEED } from '../examples/town-seed.js';

const want = [
  ['서울', 'A2', 'M'], ['서울', 'B2', 'S'], ['서울', 'G2', 'M'], ['서울', 'C1', 'XL'], ['서울', 'H1', 'S'],
  ['파리', { line: '파리 골목의 작은 빵집', input: { type: 'bakery', style: 'mediterranean', name: '르 프티 팡', levels: 2, scale: 'M', accent: '#2e5d8a', sign: { icon: 'bread', place: 'blade' } } }, 'M'],
  ['파리', { line: '센강 옆 노천 카페', input: { type: 'cafe', name: '카페 드 센', levels: 1, scale: 'S', accent: '#c0392b', props: [{ type: 'parasol', x: -.6 }, { type: 'parasol', x: .6 }] } }, 'S'],
];
const out = {}, taken = new Map();
for (const [city, which, size] of want) {
  const r = search(city), [X, Y] = toXY(r.lat, r.lng), area = makeArea(X, Y);
  const t = taken.get(X + '_' + Y) ?? [];
  let spot = null;
  for (let z = 0; z < 20 && !spot; z++) for (let x = 0; x < 20 && !spot; x++) if (canPlace(area, x, z, size, takenTiles(t))) spot = [x, z];
  if (!spot) { console.log('no spot', city, size); continue; }
  const b = typeof which === 'string' ? SEED[which] : which;
  const p = { X, Y, x: spot[0], z: spot[1], size, at: 1, b: { input: { ...b.input, scale: size }, line: b.line, at: 1 } };
  t.push(p); taken.set(X + '_' + Y, t); out[`${X}_${Y}_${spot[0]}_${spot[1]}`] = p;
}
fs.writeFileSync(new URL('../examples/world-seed.js', import.meta.url), '// Example plots that open the shared world (owner "seed"); generated by scripts/make-world-seed.mjs.\nexport const WORLD_SEED = ' + JSON.stringify(out, null, 1) + ';\n');
fs.writeFileSync('/tmp/claude-1001/-home-ubuntu-crashbang-heroes/1fe2db80-4c05-4aea-a7af-e2b5546fe96b/scratchpad/world-seed.json', JSON.stringify({ plots: out }));
